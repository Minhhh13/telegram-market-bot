import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { createHash } from 'node:crypto';

// The Dashboard editor accepts one file. Inline only our local, tested helpers;
// external version-pinned renderer imports and all environment lookups stay intact.
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
await mkdir(resolve(root, '.deploy'), { recursive: true });
for (const name of ['telegram-p2p-rate', 'telegram-marketcap']) {
  const sourcePath = resolve(root, 'supabase', name, 'index.ts');
  let source = await readFile(sourcePath, 'utf8');
  const matches = [...source.matchAll(/^import \{[^\n]+\} from '(\.\.\/_shared\/[a-z-]+\.ts)';\r?\n/gm)];
  const helpers = [];
  for (const match of matches) {
    const helper = await readFile(resolve(dirname(sourcePath), match[1]), 'utf8');
    helpers.push(helper.replace(/^export /gm, ''));
    source = source.replace(match[0], '');
  }
  if (source.includes("../_shared/")) throw new Error(`Unbundled local import in ${name}`);
  const body = helpers.join('\n') + '\n' + source;
  const hash = createHash('sha256').update(body).digest('hex');
  const output = resolve(root, '.deploy', `${name}.ts`);
  await writeFile(output, `// Generated by npm run bundle:edge; SHA-256 ${hash}\n${body}`);
  console.log(`${name}: ${output} (${hash})`);
}
